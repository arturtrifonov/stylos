#!/usr/bin/env node
// Draws the icon preset and writes everything the package carries of it.
//
//   assets/icons/manifest.yaml + the pinned font
//     → packages/ui/dist/icons/<name>.{js,d.ts,svg}   every mark in the catalogue
//     → packages/ui/src/components/icon/icons.ts      the registered marks, and the names
//
//   npm run ui:generate    (with tokens:css, the types, stories and CSS)
//
// A projection, in the same sense tokens:css is one: the manifest and the font
// are the source, and nothing here is committed. Drawing the whole catalogue
// takes about a second, which is why it is part of the build rather than a
// separate import step (docs/foundations/icons.md, FND-ICONS-14).
//
// Each mark is its own module, so a consumer's bundle carries the marks it
// imports and no others; `registerIcons` makes an imported mark resolvable by
// name. The registered marks — the ones the components and the Figma library
// already use — are in icons.ts and resolve without being imported.
//
// Why data rather than markup: the component renders <path> elements from it,
// so nothing anywhere needs {@html} — no injection shape, no sanitiser to
// keep. The shape is SPEC 0012 §4, which is also the shape a client set has
// to satisfy, so the default set and a replacement are the same type.

import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { drawPreset } from "./lib/icon-preset.mjs";

export const OUT_FILE = "packages/ui/src/components/icon/icons.ts";
export const CATALOGUE_DIR = "packages/ui/dist/icons";

const HEADER = "GENERATED by tools/build-ui-icons.mjs from assets/icons/manifest.yaml — do not edit.";

const literal = (drawing) => {
  const paths = drawing.paths
    .map((p) => (p.fillRule ? `{ d: ${JSON.stringify(p.d)}, fillRule: ${JSON.stringify(p.fillRule)} }` : `{ d: ${JSON.stringify(p.d)} }`))
    .join(", ");
  return `viewBox: ${JSON.stringify(drawing.viewBox)}, paths: [${paths}]`;
};

/**
 * One mark as an SVG file. Geometry only: no width, no height, no ARIA. The
 * size is the consumer's (a token), and the accessible name belongs on the
 * control that holds the icon, never on the icon — docs/foundations/icons.md.
 */
export function renderIconSvg(name, drawing) {
  const paths = drawing.paths
    .map((p) => `<path d="${p.d}"${p.fillRule ? ` fill-rule="${p.fillRule}"` : ""}/>`)
    .join("");
  return (
    `<!-- ${HEADER} -->\n` +
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${drawing.viewBox}" fill="currentColor" data-icon="${name}">` +
    `${paths}</svg>\n`
  );
}

/** One mark as a module: `import mark from "@stylos/ui/icons/<name>"`. */
export function renderIconModule(name, drawing) {
  return `// ${HEADER}\nexport default { name: ${JSON.stringify(name)}, ${literal(drawing)} };\n`;
}

/** Its declaration — self-contained, and assignable to RegisteredIcon. */
export function renderIconTypes(name) {
  return (
    `// ${HEADER}\n` +
    `declare const icon: { name: ${JSON.stringify(name)}; viewBox: string; paths: { d: string; fillRule?: "evenodd" }[] };\n` +
    `export default icon;\n`
  );
}

/** icons.ts: the registered drawings, and the union of every catalogue name. */
export function renderIconsModule(registered, names) {
  const entries = [...registered].map(([name, drawing]) => `  ${JSON.stringify(name)}: { ${literal(drawing)} },`).join("\n");

  return (
    `// ${HEADER}\n` +
    `// The registered marks resolve by name without an import; every other mark in\n` +
    `// the catalogue is imported from @stylos/ui/icons/<name> and registered.\n` +
    `// The shape is SPEC 0012 §4 — a replacement set satisfies the same type.\n\n` +
    `export type IconDrawing = {\n` +
    `  viewBox: string;\n` +
    `  paths: { d: string; fillRule?: "evenodd" }[];\n` +
    `};\n\n` +
    `export const icons: Record<string, IconDrawing> = {\n${entries}\n};\n\n` +
    `/** Every name in the catalogue. \`name\` accepts any string; a name resolves once registered. */\n` +
    `export type IconName =\n` +
    (names.length === 0 ? `  never;\n` : names.map((name) => `  | ${JSON.stringify(name)}`).join("\n") + ";\n")
  );
}

/**
 * Writes the catalogue into a cleared directory, so a mark the font no longer
 * declares cannot survive into the package, then icons.ts.
 */
export async function buildUiIcons(root, options) {
  const { manifest, catalogue, skipped } = await drawPreset(root, options);

  const dir = path.join(root, CATALOGUE_DIR);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  for (const [name, drawing] of catalogue) {
    writeFileSync(path.join(dir, `${name}.js`), renderIconModule(name, drawing));
    writeFileSync(path.join(dir, `${name}.d.ts`), renderIconTypes(name));
    writeFileSync(path.join(dir, `${name}.svg`), renderIconSvg(name, drawing));
  }

  const registered = new Map(manifest.registered.map((name) => [name, catalogue.get(name)]));
  mkdirSync(path.join(root, path.dirname(OUT_FILE)), { recursive: true });
  writeFileSync(path.join(root, OUT_FILE), renderIconsModule(registered, [...catalogue.keys()]));

  return { manifest, count: catalogue.size, registered: registered.size, skipped };
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  const root = path.resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
  const { manifest, count, registered, skipped } = await buildUiIcons(root);
  const axes = Object.entries(manifest.instance).map(([axis, value]) => `${axis} ${value}`).join(", ");
  console.log(
    `OK: ${count} icons (${registered} registered) from ${manifest.family} at ${axes} → ${CATALOGUE_DIR}/` +
      (skipped.length ? `; skipped ${skipped.length} not one glyph: ${skipped.join(", ")}` : "")
  );
}
