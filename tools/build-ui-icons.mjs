#!/usr/bin/env node
// Writes the drawings the Icon component renders, from the committed set.
//
//   assets/icons/svg/*.svg → packages/ui/src/components/icon/icons.ts
//
//   npm run ui:generate    (with tokens:css, the types, stories and CSS)
//
// A projection, in the same sense tokens:css is one: the SVGs are the source
// and this restates them as data the component can render without parsing
// markup at runtime. Output is gitignored and rebuilt, like every generated
// thing here.
//
// Why data rather than markup: the component renders <path> elements from it,
// so nothing anywhere needs {@html} — no injection shape, no sanitiser to
// keep. The shape is SPEC 0012 §4, which is also the shape a client set has
// to satisfy, so the default set and a replacement are the same type.

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const SOURCE_DIR = "assets/icons/svg";
export const OUT_FILE = "packages/ui/src/components/icon/icons.ts";

/**
 * The viewBox and every path of one icon file. Throws rather than emitting a
 * half-read drawing: these files are generated, so anything unreadable here
 * means the generator upstream changed and the mismatch should stop the build.
 */
export function readIconSvg(name, svg) {
  const viewBox = svg.match(/\bviewBox="([^"]+)"/)?.[1];
  if (!viewBox) throw new Error(`${name}.svg: no viewBox`);

  const paths = [...svg.matchAll(/<path\b([^>]*)\/>/g)].map((match) => {
    const attrs = match[1];
    const d = attrs.match(/\bd="([^"]+)"/)?.[1];
    if (!d) throw new Error(`${name}.svg: a <path> with no d`);
    const fillRule = attrs.match(/\bfill-rule="([^"]+)"/)?.[1];
    return fillRule ? { d, fillRule } : { d };
  });
  if (paths.length === 0) throw new Error(`${name}.svg: no <path>`);

  return { viewBox, paths };
}

/** Every icon in the set, by Material Symbols name, in filename order. */
export function readIcons(root) {
  const dir = path.join(root, SOURCE_DIR);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((file) => file.endsWith(".svg"))
    .sort()
    .map((file) => {
      const name = file.slice(0, -".svg".length);
      return [name, readIconSvg(name, readFileSync(path.join(dir, file), "utf8"))];
    });
}

/** icons.ts: the drawings, and the union of the names actually present. */
export function renderIconsModule(icons) {
  const entries = icons
    .map(([name, drawing]) => {
      const paths = drawing.paths
        .map((p) => (p.fillRule ? `{ d: ${JSON.stringify(p.d)}, fillRule: ${JSON.stringify(p.fillRule)} }` : `{ d: ${JSON.stringify(p.d)} }`))
        .join(", ");
      return `  ${JSON.stringify(name)}: { viewBox: ${JSON.stringify(drawing.viewBox)}, paths: [${paths}] },`;
    })
    .join("\n");

  return (
    `// GENERATED by tools/build-ui-icons.mjs from ${SOURCE_DIR}/ — do not edit.\n` +
    `// The set and the instance it is drawn at: assets/icons/manifest.yaml.\n` +
    `// The shape is SPEC 0012 §4 — a replacement set satisfies the same type.\n\n` +
    `export type IconDrawing = {\n` +
    `  viewBox: string;\n` +
    `  paths: { d: string; fillRule?: "evenodd" }[];\n` +
    `};\n\n` +
    `export const icons: Record<string, IconDrawing> = {\n${entries}\n};\n\n` +
    `/** The names this build carries. \`name\` accepts any string; this is what resolves. */\n` +
    `export type IconName =\n` +
    (icons.length === 0 ? `  never;\n` : icons.map(([name]) => `  | ${JSON.stringify(name)}`).join("\n") + ";\n")
  );
}

/** Writes icons.ts. Returns the path written, relative to the root. */
export function buildUiIcons(root) {
  const icons = readIcons(root);
  writeFileSync(path.join(root, OUT_FILE), renderIconsModule(icons));
  return OUT_FILE;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  const root = path.resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
  const written = buildUiIcons(root);
  console.log(`OK: ${readIcons(root).length} drawings — ${written}`);
}
