#!/usr/bin/env node
// Projects figma/text-styles.yaml onto CSS classes — the text export of
// @stylos/ui, decided in-session 2026-09-06 alongside the record itself.
//
//   figma/text-styles.yaml → packages/ui/dist/text.css
//
//   npm run ui:generate    (after tokens:css, whose custom properties it reads)
//
// One class per recorded style, named by the style's slug: "text/normal/medium"
// → .stylos-text-normal-medium. Every declaration is a var() reference into
// tokens.css — the same projection discipline as tokens:css itself, no value
// improved on the way through. `text case: uppercase` becomes text-transform;
// a width off 100 becomes font-stretch. Paragraph spacing has no
// non-opinionated CSS analog (it is the space between paragraphs, which is
// the consumer's layout), so it is emitted as a private custom property
// `--stylos-paragraph-spacing` on the class, for the consumer to apply.
//
// A style carrying an `unresolved` binding is not projected: a class with a
// dangling var() would fall back silently, which is worse than absence. It is
// named in the output header instead, so the gap is visible where the file
// is read.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { parse } from "./lib/yaml.mjs";
import { slug, property } from "./build-css.mjs";

export const SOURCE = "figma/text-styles.yaml";
export const OUT_FILE = "packages/ui/dist/text.css";

/** "font/family/normal" → var(--stylos-font-family-normal) */
function varRef(alias) {
  return `var(${property(alias)})`;
}

const DECLARATIONS = [
  ["font family", "font-family"],
  ["font weight", "font-weight"],
  ["font size", "font-size"],
  ["line height", "line-height"],
  ["letter spacing", "letter-spacing"],
];

/** Renders the stylesheet from the parsed record. */
export function renderTextCss(record) {
  const styles = record.get("styles");
  const skipped = [];
  const rules = [];

  for (const [name, entry] of styles) {
    if (entry.has("unresolved")) {
      skipped.push(name);
      continue;
    }
    const lines = [];
    for (const [key, cssProperty] of DECLARATIONS) {
      if (entry.has(key)) lines.push(`  ${cssProperty}: ${varRef(entry.get(key))};`);
    }
    if (entry.get("text case") === "uppercase") lines.push("  text-transform: uppercase;");
    if (entry.has("width")) lines.push(`  font-stretch: ${entry.get("width")}%;`);
    if (entry.has("paragraph spacing")) {
      lines.push(`  --stylos-paragraph-spacing: ${varRef(entry.get("paragraph spacing"))};`);
    }
    rules.push(`.stylos-${slug(name)} {\n${lines.join("\n")}\n}`);
  }

  const header =
    `/* GENERATED by tools/build-text-css.mjs from ${SOURCE} — do not edit.\n` +
    ` * ${rules.length} text styles as classes, every value a reference into tokens.css —\n` +
    ` * link tokens.css and fonts.css beside this file.` +
    (skipped.length
      ? `\n * NOT projected (unresolved bindings in the record): ${skipped.join(", ")}.`
      : "") +
    `\n */\n`;
  return { css: [header, ...rules].join("\n") + "\n", count: rules.length, skipped };
}

/** Reads the record and writes the stylesheet. */
export function buildTextCss(root) {
  const sourcePath = path.join(root, SOURCE);
  if (!existsSync(sourcePath)) {
    throw new Error(`${SOURCE} is missing — run tools/import-styles.mjs first`);
  }
  const record = parse(readFileSync(sourcePath, "utf8"), { filename: SOURCE });
  const { css, count, skipped } = renderTextCss(record);
  mkdirSync(path.dirname(path.join(root, OUT_FILE)), { recursive: true });
  writeFileSync(path.join(root, OUT_FILE), css);
  return { outPath: OUT_FILE, count, skipped };
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  const root = path.resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
  const { outPath, count, skipped } = buildTextCss(root);
  console.log(
    `OK: ${count} text style classes → ${outPath}` +
      (skipped.length ? ` — skipped (unresolved): ${skipped.join(", ")}` : "")
  );
}
