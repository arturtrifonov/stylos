import test from "node:test";
import assert from "node:assert/strict";

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

import {
  buildUiIcons,
  renderIconModule,
  renderIconSvg,
  renderIconTypes,
  renderIconsModule,
  CATALOGUE_DIR,
  OUT_FILE,
} from "./build-ui-icons.mjs";
import { fakeFont, scratchRoot } from "./lib/icon-fixtures.mjs";

const drawing = { viewBox: "0 -960 960 960", paths: [{ d: "M1 -2Z" }] };

test("renderIconSvg writes geometry only — no size, no ARIA", () => {
  const svg = renderIconSvg("search", drawing);

  assert.match(svg, /GENERATED by tools\/build-ui-icons\.mjs/);
  assert.ok(svg.includes('viewBox="0 -960 960 960"'), "carries the upstream 960 em box");
  assert.ok(svg.includes('fill="currentColor"'), "inherits colour from the control");
  assert.ok(svg.includes('data-icon="search"'));
  assert.ok(svg.includes('<path d="M1 -2Z"/>'));

  // Size is the consumer's token, and the accessible name belongs on the
  // control that holds the icon — docs/foundations/icons.md.
  assert.ok(!/\swidth=/.test(svg), "no width");
  assert.ok(!/\sheight=/.test(svg), "no height");
  assert.ok(!/aria-|role=/.test(svg), "no ARIA");
});

test("a mark's module exports its name with its drawing, and its declaration matches", () => {
  assert.ok(
    renderIconModule("search", drawing).endsWith(
      'export default { name: "search", viewBox: "0 -960 960 960", paths: [{ d: "M1 -2Z" }] };\n'
    )
  );
  const types = renderIconTypes("search");
  assert.ok(types.includes('declare const icon: { name: "search"; viewBox: string; paths: { d: string; fillRule?: "evenodd" }[] };'));
  assert.ok(types.endsWith("export default icon;\n"));
});

test("renderIconsModule emits the registered drawings and a union of every catalogue name", () => {
  const module = renderIconsModule(
    new Map([
      ["add", { viewBox: "0 -960 960 960", paths: [{ d: "M1Z" }] }],
      ["check", { viewBox: "0 -960 960 960", paths: [{ d: "M2Z", fillRule: "evenodd" }] }],
    ]),
    ["add", "check", "rocket_launch"]
  );

  assert.match(module, /GENERATED by tools\/build-ui-icons\.mjs/);
  assert.ok(module.includes('"add": { viewBox: "0 -960 960 960", paths: [{ d: "M1Z" }] },'));
  assert.ok(module.includes('{ d: "M2Z", fillRule: "evenodd" }'));
  assert.ok(module.includes('export type IconName =\n  | "add"\n  | "check"\n  | "rocket_launch";'));
  // The shape a replacement set has to satisfy is the same one — SPEC 0012 §4.
  assert.ok(module.includes("export type IconDrawing"));
});

test("renderIconsModule on an empty set still type-checks", () => {
  const module = renderIconsModule(new Map(), []);
  assert.ok(module.includes("export const icons: Record<string, IconDrawing> = {\n\n};"));
  assert.ok(module.includes("export type IconName =\n  never;"));
});

test("buildUiIcons writes every catalogue mark three ways, and icons.ts with the registered ones", async () => {
  const root = scratchRoot();
  const names = ["add", "chevron_right", "search"];
  const result = await buildUiIcons(root, { open: () => fakeFont(names), names: () => names });

  assert.equal(result.count, 3);
  assert.equal(result.registered, 2);
  assert.deepEqual(readdirSync(path.join(root, CATALOGUE_DIR)).sort(), [
    "add.d.ts", "add.js", "add.svg",
    "chevron_right.d.ts", "chevron_right.js", "chevron_right.svg",
    "search.d.ts", "search.js", "search.svg",
  ]);

  const module = readFileSync(path.join(root, OUT_FILE), "utf8");
  assert.ok(module.includes('"chevron_right": {'));
  assert.ok(module.includes('"search": {'));
  assert.ok(!module.includes('"add": {'), "a mark outside the registered list is imported, not bundled");
  assert.ok(module.includes('  | "add"'), "but its name is in the union");
});

test("buildUiIcons clears the catalogue, so a mark the font dropped cannot survive", async () => {
  const root = scratchRoot();
  mkdirSync(path.join(root, CATALOGUE_DIR), { recursive: true });
  writeFileSync(path.join(root, CATALOGUE_DIR, "dropped.js"), "");

  const names = ["chevron_right", "search"];
  await buildUiIcons(root, { open: () => fakeFont(names), names: () => names });

  assert.ok(!readdirSync(path.join(root, CATALOGUE_DIR)).includes("dropped.js"));
});
