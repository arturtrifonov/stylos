#!/usr/bin/env node
// Builds the font export of @stylos/ui — decided in-session, 2026-09-06:
// the package that names Georama in tokens.css also supplies it.
//
//   assets/fonts/*.woff2 (the FONT_FACES subsets) → packages/ui/dist/assets/fonts/
//   the @font-face rules for them                 → packages/ui/dist/fonts.css
//
//   npm run ui:generate    (with tokens:css, the types, stories and CSS)
//
// The faces are the ones tools/lib/theme.mjs declares for the registry-viewer
// pages — same files, same ranges, rendered by the same fontFacesCss — so the
// package and the viewer cannot drift apart. The woff2 are committed under
// assets/fonts/ and copied, never fetched: a font update is a deliberate
// commit with a diff, not a side effect of a build. fonts.css is separate
// from tokens.css for the same reason the CSS export is: tokens.css is the
// file a client theme overrides, and a client with its own brand face links
// its own faces instead of these.

import { copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { FONT_FACES, fontFacesCss } from "./lib/theme.mjs";

export const SOURCE_DIR = "assets/fonts";
export const OUT_DIR = "packages/ui/dist";
export const FONTS_CSS = "fonts.css";

/** fonts.css: a generated header naming the families, then the faces. */
export function renderFontsCss(faces) {
  const families = [...new Set(faces.map((face) => face.family))].join(", ");
  const header =
    `/* GENERATED by tools/build-ui-fonts.mjs — do not edit.\n` +
    ` * Self-hosted subsets of ${families}, served from ./assets/fonts/.\n` +
    ` * tokens.css names these families; this file supplies them. A client\n` +
    ` * theme with its own brand face links its own faces instead.\n` +
    ` */\n`;
  return `${header}\n${fontFacesCss()}\n`;
}

/**
 * Copies each face's woff2 and writes fonts.css. Returns the written paths,
 * relative to the root, fonts.css last. A missing source file fails the
 * build rather than shipping a stylesheet whose `src` dangles.
 */
export function buildUiFonts(root) {
  const outFontsDir = path.join(root, OUT_DIR, "assets/fonts");
  mkdirSync(outFontsDir, { recursive: true });

  const written = [];
  for (const face of FONT_FACES) {
    const source = path.join(root, SOURCE_DIR, face.file);
    if (!existsSync(source)) {
      throw new Error(`${SOURCE_DIR}/${face.file} is missing — FONT_FACES names it`);
    }
    copyFileSync(source, path.join(outFontsDir, face.file));
    written.push(`${OUT_DIR}/assets/fonts/${face.file}`);
  }

  writeFileSync(path.join(root, OUT_DIR, FONTS_CSS), renderFontsCss(FONT_FACES));
  written.push(`${OUT_DIR}/${FONTS_CSS}`);
  return written;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  const root = path.resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
  const written = buildUiFonts(root);
  console.log(`OK: ${written.length} files — ${written.join(", ")}`);
}
