#!/usr/bin/env node
// Applies complete recorded body and heading text styles to content HTML.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SOURCE, textStyleDeclarations } from "./build-text-css.mjs";
import { property } from "./build-css.mjs";
import { parse } from "./lib/yaml.mjs";

export const OUT_FILE = "packages/ui/dist/prose.css";
export const SIZES = ["extra small", "small", "medium", "large", "extra large"];

export function renderProseCss(record) {
  const styles = record.get("styles");
  const rules = [];
  function rule(selector, name) {
    const entry = styles.get(name);
    if (!entry) throw new Error(`Content typography requires text style ${name}`);
    // A partial or unresolved style cannot silently fall back to browser defaults.
    for (const property of ["font family", "font weight", "font size", "line height", "letter spacing"]) {
      if (!entry.has(property)) throw new Error(`Text style ${name} is missing ${property}`);
    }
    if (name.startsWith("text/") && !entry.has("paragraph spacing")) {
      throw new Error(`Text style ${name} is missing paragraph spacing`);
    }
    rules.push(`${selector} {\n${textStyleDeclarations(name, entry)}\n}`);
  }
  // Default and explicit styles share the same projection. The name in the
  // public attribute is the complete Figma style name, never a token measure.
  rule(".stylos-prose", "text/base/medium");
  for (const role of ["base", "emphasis"]) {
    for (const size of SIZES) {
      const name = `text/${role}/${size}`;
      const selector = `.stylos-prose[data-text-style="${name}"]`;
      rule(selector, name);
    }
  }
  for (let level = 1; level <= 6; level++) {
    rule(`.stylos-prose :where(h${level})`, `heading/h${level}`);
  }
  // FND-TYPOGRAPHY-11: the approved B profile belongs to document layout,
  // independently of the complete heading style and selected body size.
  const gap = (step) => `var(${property(`dimension/gap/g-${step}`)})`;
  for (const [headings, before, after] of [
    ["h1, h2", "3_500", "1_500"],
    ["h3, h4", "3_000", "1_000"],
    ["h5, h6", "2_000", "1_000"],
  ]) {
    rules.push(`.stylos-prose :where(${headings}) {\n  margin-block-start: ${gap(before)};\n  margin-block-end: ${gap(after)};\n}`);
  }
  // FND-TYPOGRAPHY-12/13: normal block flow collapses adjacent positive
  // margins to their maximum. Paragraphs contribute only an after-gap.
  rules.push(`.stylos-prose :where(p) {\n  margin-block-start: ${gap("0_000")};\n  margin-block-end: var(--stylos-paragraph-spacing);\n}`);
  const blocks = ":where(h1, h2, h3, h4, h5, h6, p)";
  rules.push(`.stylos-prose > ${blocks}:first-child {\n  margin-block-start: ${gap("0_000")};\n}`);
  rules.push(`.stylos-prose > ${blocks}:last-child {\n  margin-block-end: ${gap("0_000")};\n}`);
  return `/* GENERATED by tools/build-prose-css.mjs — do not edit.
 * Typography: ${SOURCE}. Document spacing: FND-TYPOGRAPHY-11/12/13.
 * Link tokens.css and fonts.css separately. text.css is not required.
 */\n\n${rules.join("\n\n")}\n`;
}

export function buildProseCss(root) {
  const record = parse(readFileSync(path.join(root, SOURCE), "utf8"), { filename: SOURCE });
  const css = renderProseCss(record);
  const outPath = path.join(root, OUT_FILE);
  mkdirSync(path.dirname(outPath), { recursive: true });
  writeFileSync(outPath, css);
  return OUT_FILE;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
  console.log(`OK: content typography → ${buildProseCss(root)}`);
}
