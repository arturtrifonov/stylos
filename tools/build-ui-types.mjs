#!/usr/bin/env node
// Writes packages/ui/src/components/<name>/props.ts from the registry entry's
// `api`, one file per component directory that exists under src/components.
//
//   npm run ui:generate    (with tokens:css and the stories, SPEC 0009 §4)
//
// The mapping is SPEC 0009 §3 — props ↔ the entry's `api`, 1:1:
//
//   variant  → one prop, camelCased name, values as a string union, verbatim
//   text     → a string prop
//   boolean  → a boolean prop
//   instance → a prop taking a component or snippet
//   slot     → a snippet, named `children` where the entry has exactly one
//
// This is the condition under which TypeScript was accepted (ADR 0002): the
// types are generated from the contract, never hand-written, so a wrong value
// is a compile error and the 1:1 mapping is checked by the compiler rather
// than by eye. The output is gitignored and rebuilt, like every generated
// thing.
//
// Only components with a directory are generated: a directory appears when a
// component's `.svelte` is written, which per §5 is the same session its
// contract was corrected. Generating all 114 entries would type-check nothing
// and produce 100+ files nothing imports.

import { existsSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { loadRegistry, slugPath } from "./lib/registry.mjs";

export const COMPONENTS_DIR = "packages/ui/src/components";

/** `number text` → `numberText`, `text case` → `textCase`. */
export function camelName(name) {
  const words = name.split(/\s+/).filter(Boolean);
  return words
    .map((word, i) => {
      const clean = word.replace(/[^a-zA-Z0-9]/g, "");
      return i === 0 ? clean.toLowerCase() : clean.charAt(0).toUpperCase() + clean.slice(1).toLowerCase();
    })
    .join("");
}

/** `Checkbox Input` → `CheckboxInput` — the component's export name. */
export function pascalName(id) {
  return id
    .split(/[\s/]+/)
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");
}

/** `Checkbox Input` → `CheckboxInputProps`. */
export function typeName(id) {
  return `${pascalName(id)}Props`;
}

function union(property) {
  const values = (property.values ?? []).map((entry) => JSON.stringify(entry.value));
  if (values.length === 0) {
    throw new Error(`variant property "${property.name}" has no values`);
  }
  return values.join(" | ");
}

/**
 * The TypeScript field for one `api` property, or null for a kind that maps
 * onto nothing (there is none today; a new kind fails loudly instead).
 */
export function fieldFor(property, { soleSlot = false } = {}) {
  const propName = property.kind === "slot" && soleSlot ? "children" : camelName(property.name);
  const type = {
    variant: () => union(property),
    text: () => "string",
    boolean: () => "boolean",
    instance: () => "Component | Snippet",
    slot: () => "Snippet",
  }[property.kind];
  if (!type) {
    throw new Error(`property "${property.name}" has unknown kind "${property.kind}"`);
  }
  return { propName, type: type() };
}

/** The whole props.ts for one entry. */
export function renderProps(entry) {
  const api = Array.isArray(entry.api) ? entry.api : [];
  if (api.length === 0) {
    throw new Error(`"${entry.id}" has no api to generate props from`);
  }

  const slots = api.filter((property) => property.kind === "slot");
  const fields = api.map((property) => {
    const { propName, type } = fieldFor(property, { soleSlot: slots.length === 1 });
    const lines = [];
    if (property.description) {
      lines.push(`  /** ${property.description.replace(/\*\//g, "*\\/")} */`);
    }
    // Every prop is optional: `default` lives in the wrapper, and a slot or
    // instance may simply be absent. The union still rejects a wrong value.
    lines.push(`  ${propName}?: ${type};`);
    return lines.join("\n");
  });

  const needsSvelteTypes = api.some(
    (property) => property.kind === "instance" || property.kind === "slot"
  );
  const importLine = needsSvelteTypes
    ? `import type { Component, Snippet } from "svelte";\n\n`
    : "";

  return (
    `// GENERATED by tools/build-ui-types.mjs from ` +
    `docs/components/registry/${slugPath(entry.id)}.yaml — do not edit.\n` +
    `// Props ↔ api, 1:1 (SPEC 0009 §3). A divergence is a contract change, not an edit here.\n\n` +
    importLine +
    `export type ${typeName(entry.id)} = {\n${fields.join("\n")}\n};\n`
  );
}

/**
 * Every component directory under src/components, matched to its registry
 * entry by the same slug rule the registry files follow.
 */
export function builtComponents(root, entries) {
  const dir = path.join(root, COMPONENTS_DIR);
  if (!existsSync(dir)) return [];
  const bySlug = new Map(entries.map((entry) => [slugPath(entry.id), entry]));
  return readdirSync(dir, { withFileTypes: true })
    .filter((dirent) => dirent.isDirectory())
    .map((dirent) => {
      const entry = bySlug.get(dirent.name);
      if (!entry) {
        throw new Error(
          `${COMPONENTS_DIR}/${dirent.name}/ matches no registry entry — ` +
            `the directory name must be the slug of a registry id`
        );
      }
      return entry;
    });
}

export function buildTypes(root) {
  const entries = loadRegistry(root);
  const built = builtComponents(root, entries);
  const written = [];
  for (const entry of built) {
    const file = path.join(root, COMPONENTS_DIR, slugPath(entry.id), "props.ts");
    writeFileSync(file, renderProps(entry));
    written.push(path.relative(root, file));
  }
  return written;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  // Root-resolved from this file's location, so the generator runs correctly
  // from the repository root and from packages/ui's prebuild alike.
  const root = path.resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
  const written = buildTypes(root);
  console.log(`OK: ${written.length} props.ts generated — ${written.join(", ")}`);
}
